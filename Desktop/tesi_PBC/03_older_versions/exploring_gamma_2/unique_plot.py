import matplotlib.pyplot as plt  # for plotting
import numpy as np  # for doing stuff with numbers
import pandas as pd  # to easily print matrices

##########################################
# 1. Define parameters for a QW on a line
##########################################
num_sites = 20
target_site = num_sites // 2  # opposite end
num_gamma2_points = 400  # horizontal resolution
num_tau_points = 400  # vertical resolution
gamma2_min = 0.0
gamma2_max = 1.0
tau_min = 0.02
tau_max = 4.00

# The three phi values requested
phi_values = [0.0, 0.078540, 0.157080]
M = 2000

# Create a figure with 3 subplots side-by-side sharing the y-axis
fig, axes = plt.subplots(1, 3, figsize=(11, 4), sharey=True , gridspec_kw={'wspace': 0.1})
extent = [gamma2_min, gamma2_max, tau_min, tau_max]

ticks = [0.0, 0.25, 0.5, 0.75, 1.0]
tick_labels = [rf'$0.0$', rf'$0.25$', rf'$0.50$', rf'$0.75$', rf'$1.0$']

for i, phi_1 in enumerate(phi_values):
  # Load the matrix generated by the C++ simulation engine for each phi value
  filename = f'RESULTS_mean_hitting_time_PVM_phi1_{phi_1:.6f}_N_{num_sites}_resolution_{num_gamma2_points}x{num_tau_points}_{M}_runs.txt'
  mean_hitting_times = np.loadtxt(filename)

  # Plot heatmap with fixed colorbar range (0 to 200)
  im = axes[i].imshow(
      mean_hitting_times,
      extent=extent,
      origin='lower',
      aspect='auto',
      cmap='viridis_r',
      vmin=0,
      vmax=200,
  )

  fonts = 12
  axes[i].set_xlabel(rf'$\gamma_2$', fontsize=fonts)
  if i == 0:
    axes[i].set_ylabel(rf'$\tau$', fontsize=fonts)

  # Title removed per instructions

  axes[i].set_xticks(ticks)
  axes[i].set_xticklabels(tick_labels)

# Adjust layout to leave space on the right for the single colorbar
fig.subplots_adjust(right=0.88)
cbar_ax = fig.add_axes([0.91, 0.15, 0.025, 0.7])
cbar = fig.colorbar(im, cax=cbar_ax)
cbar.set_label(rf'$\langle n \tau \rangle$', fontsize=12)

# Save the combined figure as a single PDF
output_filename = (
    f'CPLUSPLUS_gamma2_vs_tau_mean_hitting_time_3phi_comparison.pdf'
)
plt.savefig(output_filename, bbox_inches='tight')
print(f'Saved combined PDF as: {output_filename}')
plt.show()