import numpy as np # for doing stuff with numbers
import matplotlib.pyplot as plt # for plotting
import pandas as pd # to easily print matrices

# BEFORE RUNNING THIS, ENSURE THE PARAMETERS MATCH PERFECTLY!!!

##########################################
# 1. define parameters for a qw on a line
##########################################

# test different phis and taus (2D GRID) for fixed size N
num_sites = 20
target_site = num_sites // 2 # opposite end
num_phi_points = 170 # horizontal resolution
num_tau_points = 170 # vertical resolution
phi_min = -np.pi/num_sites
phi_max = +np.pi/num_sites
tau_min = 0.60
tau_max = 3.20

gamma_2 = 0.0
M = 2000

# smearing parameter matching the C++ choice ("NONE", "UNIFORM", or "GAUSSIAN")
smearing_type = "UNIFORM"
smearing_error = 0.25

# Load the matrix generated by the C++ simulation engine
mean_hitting_times = np.loadtxt(f'RESULTS_SMEARING_{smearing_type}_{smearing_error:.6f}_mean_hitting_time_PVM_gamma2_{gamma_2:.6f}_N_{num_sites}_resolution_{num_phi_points}x{num_tau_points}_{M}_runs.txt')

##########################################
# parts 2. 3. 4. are in the C++ code
##########################################

##########################################
# 5. plot of the 2d mean hitting time grid
##########################################

plt.figure(figsize=(8,6))
extent = [phi_min, phi_max, tau_min, tau_max]

im = plt.imshow(
    mean_hitting_times, 
    extent=extent, 
    origin='lower', 
    aspect='auto', 
    cmap='viridis_r'
)

fonts = 12
plt.xlabel(rf'$\phi_1$', fontsize = fonts)
plt.ylabel(rf'$\tau$', fontsize = fonts)
plt.title(rf'$N = {num_sites}$, $i={target_site}$, $\gamma_2 = {gamma_2}$', fontsize = fonts)

ticks = [-np.pi/num_sites, -0.5*np.pi/num_sites, 0, 0.5*np.pi/num_sites , np.pi/num_sites]
tick_labels = [rf'$-\pi/N$', rf'$-\pi/(2N)$', rf'$0$', rf'$+\pi/(2N)$', rf'$+\pi/N$']
plt.xticks(ticks, tick_labels)

cbar = plt.colorbar(im)
filename = rf'CPLUSPLUS_SMEARING_{smearing_type}_{smearing_error:.6f}_phi1_vs_tau_mean_hitting_time_PVM_gamma2_{gamma_2}_N_{num_sites}_resolution_{num_phi_points}x{num_tau_points}'
plt.savefig(filename+'.pdf')
plt.show()